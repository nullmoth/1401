"""Writes mac/tests/efi_rules/vectors.json: cases the Python checker decides, which the Mac app's Swift checker must
decide the same way (mac/tests/efi_rules/main.swift). tests/test_efi_rules_vectors.py fails when the file is stale.

python3 tools/efi_rules_vectors.py            # rewrite the file
"""
import base64
import copy
import json
import os
import plistlib
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from p1401 import efi_rules  # noqa: E402
from tests import test_efi_rules as t  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "mac", "tests", "efi_rules", "vectors.json")


def cases():
    out, blobs = [], {}
    edge = t.engine_like()
    del edge["Misc"]["Security"]          # a missing key takes the rule's default
    edge["Booter"]["Quirks"]["DevirtualiseMmio"] = 1   # an integer is not a boolean
    configs = [("engine-like", t.engine_like()), ("missing keys", edge), ("empty", {})]
    for label, hw, darwin in t.SHAPES:
        facts = efi_rules.facts_from_report(hw, darwin)
        built, _ = t.run_policy(t.engine_like(), hw, darwin)
        for clabel, cfg in configs + [("policy-built", built)]:
            for scope in ("stick", "installed"):
                for extra in ([], ["firmware_no_dmar"]):
                    f = dict(facts, fact=sorted(set(facts["fact"]) | set(extra)))
                    issues = efi_rules.check(cfg, f, scope)
                    fixed = efi_rules.fix(cfg, issues)
                    out.append({"name": f"{label} / {clabel} / {scope}{' / no DMAR' if extra else ''}", "facts": f, "scope": scope,
                                "config": blobs.setdefault(base64.b64encode(plistlib.dumps(cfg)).decode(), f"c{len(blobs)}"),
                                "issues": [i["id"] for i in issues],
                                "after_fix": [i["id"] for i in efi_rules.check(fixed, f, scope)]})
    return out, {v: k for k, v in blobs.items()}


def cpu_classes():
    """The CPU families each real brand string (from users' OpenCore logs) belongs to, with no codename: what the Mac
    app has to work out from the name alone."""
    with open(os.path.join(os.path.dirname(OUT), "cpu_names.txt"), encoding="utf-8") as fh:
        names = [n.strip() for n in fh if n.strip()]
    out = []
    for n in names:
        vendor = "AMD" if "AMD" in n else "Intel" if "Intel" in n else ""
        f = efi_rules.facts_from_report({"CPU": {"Manufacturer": vendor, "Processor Name": n, "Codename": ""}}, "")
        out.append({"vendor": vendor, "name": n, "classes": f["cpu_class"]})
    return out


def render():
    out, configs = cases()
    return json.dumps({"about": "generated by tools/efi_rules_vectors.py; do not edit. configs: key -> base64 XML plist",
                       "configs": configs, "cases": out, "cpu_names": cpu_classes()}, indent=1, sort_keys=True) + "\n"


if __name__ == "__main__":
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(render())
    os.replace(tmp, OUT)
    print(f"wrote {OUT}")
